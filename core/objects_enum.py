"""The ObjType enum: the OBJECTS_ENUM expansion of the object table.

In C the object-type enum is not written anywhere: include/objects.h is
a table of OBJECT(...) rows and the preprocessor expands it -- once
into `enum OBJECTS_ENUM` (objclass.h), and once into the objects[]
struct array (objects.c).  The Python port expands the same table twice
as well:

- `objects_data._OBJTYPE_NAMES` -- the name column as data, next to the
  rows it names;
- this module -- the enum itself, spelled out in the C order.

Why the member list is written out here.  `ObjType` has 480 members.
Built with the functional `IntEnum("ObjType", {...})` API from a table
of names, the members exist only at run time: a type checker sees a
bare `type[ObjType]` with no attributes, so every `ObjType.SHORT_SWORD`
in the tree is an error ("type[ObjType] has no attribute ...") -- 283
of them across 11 files -- and no annotation on the use sites can help,
because the problem is that the members are unknowable, not that they
are untyped.  A literal class body is the one form mypy reads
statically, and then every C-style integer definition drawn off the
enum (`LAST_GENERIC = ObjType.GENERIC_VENOM.value` and the rest of the
markers below, plus all the object-type lookups in weapon.py, o_init.py,
worn.py, ...) type checks exactly as written, with no annotation.

Why it is its own module, and not part of objects.py: the member list
is long, it is generated by hand from the table (not derived), and it
imports nothing -- so it stays isolated from the API module, which is
free to be the assembly point (BASES, object_type(), the sanity checks,
the re-exports).  The chain is still one-way:

    objects_enum   ->  (nothing)
    objects_data   ->  objects_defs
    objects        ->  objects_enum + objects_defs + objects_data

Values: C numbering, position for position -- slot 0 is the real
strange object, slots 1..17 are the generic class placeholders, and
row i of OBJECTS belongs to the member with value i.  Only
STRANGE_OBJECT needs an explicit value; everything else is `auto()`
(the C enum's implicit "previous + 1"), so adding a row means adding
one name in one place instead of renumbering 480 integers by hand.

The table order now exists twice -- here and in `_OBJTYPE_NAMES` -- the
same way it exists twice in C.  core.objects._validate() asserts the
two agree (same names, same order, same values), so a row added to one
expansion and not the other fails at import time.

Import core.objects (the public API); this module is only its source.
"""

